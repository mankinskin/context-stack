/// A 16³ voxel chunk stored in the server database.
#[derive(Clone, Debug)]
pub struct VoxelChunk {
    /// Spatial hash from (cx, cy, cz).
    pub chunk_hash: u64,
    pub cx: i32,
    pub cy: i32,
    pub cz: i32,
    /// Serialized `OctreeNode` array for this chunk.
    pub octree_data: Vec<u8>,
    /// Tick number of last modification.
    pub last_modified: u64,
}

/// A single-voxel delta applied to a chunk.
#[derive(Clone, Debug)]
pub struct VoxelDelta {
    pub delta_id: u64,
    pub chunk_hash: u64,
    pub local_x: u8,
    pub local_y: u8,
    pub local_z: u8,
    pub new_color: u32,
    pub tick: u64,
}

/// Player state stored in the server database.
#[derive(Clone, Debug)]
pub struct PlayerRow {
    pub identity: PlayerIdentity,
    pub entity_id: u64,
    pub position: (f32, f32, f32),
    pub velocity: (f32, f32, f32),
    pub rotation_yaw: f32,
    pub hp: i32,
    pub max_hp: i32,
    pub mana: i32,
    pub max_mana: i32,
    pub skin_color: u32,
    pub last_tick: u64,
}

impl Default for PlayerRow {
    fn default() -> Self {
        Self {
            identity: PlayerIdentity::local(),
            entity_id: 0,
            position: (0.0, 10.0, 0.0),
            velocity: (0.0, 0.0, 0.0),
            rotation_yaw: 0.0,
            hp: 100,
            max_hp: 100,
            mana: 50,
            max_mana: 50,
            skin_color: 0xFFCCAA,
            last_tick: 0,
        }
    }
}

/// Item blueprint defining a craftable/equippable item.
#[derive(Clone, Debug)]
pub struct ItemBlueprint {
    pub blueprint_id: u32,
    pub name: String,
    /// Serialized 8³ mini-SVO for item appearance.
    pub voxel_data: Vec<u8>,
    pub base_damage: i32,
    pub weight: f32,
    pub item_type: ItemType,
}

/// Type classification for items.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum ItemType {
    Weapon = 0,
    Tool = 1,
    Block = 2,
    Consumable = 3,
}

impl ItemType {
    pub fn from_u8(v: u8) -> Self {
        match v {
            0 => Self::Weapon,
            1 => Self::Tool,
            2 => Self::Block,
            3 => Self::Consumable,
            _ => Self::Block,
        }
    }
}

/// A slot in a player's inventory.
#[derive(Clone, Debug)]
pub struct InventorySlot {
    pub slot_id: u64,
    pub owner: PlayerIdentity,
    pub blueprint_id: u32,
    pub quantity: u32,
    pub slot_index: u8,
}

/// Combat event generated by the server when an attack lands.
#[derive(Clone, Debug)]
pub struct CombatEvent {
    pub event_id: u64,
    pub attacker: PlayerIdentity,
    pub target: PlayerIdentity,
    pub damage: i32,
    pub hit_pos: (f32, f32, f32),
    pub tick: u64,
}

